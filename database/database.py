import os
import json
import psycopg
from dotenv import load_dotenv

load_dotenv()

def get_connection():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is missing from .env")

    return psycopg.connect(database_url)


def create_database():
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS predictions (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL REFERENCES users(id),
                    condition_name TEXT NOT NULL,
                    result TEXT NOT NULL,
                    risk TEXT NOT NULL,
                    timestamp TEXT NOT NULL,
                    inputs_json TEXT
                )
            """)


def save_prediction_to_db(
    user_id, condition, result, risk, timestamp, inputs
):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO predictions
                (user_id, condition_name, result, risk, timestamp, inputs_json)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (
                    user_id,
                    condition,
                    result,
                    risk,
                    timestamp,
                    json.dumps(inputs),
                ),
            )


def get_user_predictions(user_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT condition_name, result, risk, timestamp, inputs_json
                FROM predictions
                WHERE user_id = %s
                ORDER BY timestamp DESC
                """,
                (user_id,),
            )
            rows = cursor.fetchall()

    records = []
    for cond, result, risk, timestamp, inputs_json in rows:
        try:
            inputs = json.loads(inputs_json) if inputs_json else {}
        except (TypeError, ValueError):
            inputs = {}

        records.append({
            "condition": cond,
            "result": result,
            "risk": risk,
            "timestamp": timestamp,
            "inputs": inputs,
        })

    return records


def clear_user_predictions(user_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                "DELETE FROM predictions WHERE user_id = %s",
                (user_id,),
            )

