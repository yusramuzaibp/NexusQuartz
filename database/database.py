def get_connection():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is missing from .env")

    return psycopg.connect(database_url)


@contextmanager
def db_cursor():
    """Provide a database cursor for existing admin authentication code."""
    with get_connection() as conn:
        with conn.cursor() as cursor:
            yield cursor


def create_database():
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL
                )
            """)

            
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS predictions (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL REFERENCES users(id),
                    condition_name TEXT NOT NULL,
                    result TEXT NOT NULL,
                    risk TEXT NOT NULL,
                    timestamp TEXT NOT NULL,
                    inputs_json TEXT
                )
            """)

            
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS patients (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    doctor_id INTEGER NOT NULL REFERENCES users(id),
                    patient_code TEXT NOT NULL,
                    name TEXT NOT NULL,
                    age INTEGER NOT NULL,
                    sex TEXT NOT NULL,
                    contact TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE (doctor_id, patient_code)
                )
            """)
            cursor.execute("""
                ALTER TABLE predictions
                  ADD COLUMN IF NOT EXISTS patient_id INTEGER
                   REFERENCES patients(id)
            """)
            
            cursor.execute("""
                 ALTER TABLE users
                    ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'user'
            """)
            cursor.execute("""
                ALTER TABLE users
                ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'active'
           """)
            cursor.execute("""
               ALTER TABLE users
               ADD COLUMN IF NOT EXISTS created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
       """)
def migrate_patient_data_to_encrypted():
    """
    One-time migration: change patients.age to TEXT and encrypt existing
    patient name, age, sex and contact values. Safe to run more than once.
    Run this against the backup database first.
    """
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                ALTER TABLE patients
                ALTER COLUMN age TYPE TEXT
                USING age::TEXT
            """)

            cursor.execute("""
                SELECT id, name, age, sex, contact
                FROM patients
            """)
            rows = cursor.fetchall()

            for row in rows:
                patient_id, name, age, sex, contact = row
                cursor.execute("""
                    UPDATE patients
                    SET name = %s,
                        age = %s,
                        sex = %s,
                        contact = %s
                    WHERE id = %s
                """, (
                    encrypt_text(name),
                    encrypt_text(age),
                    encrypt_text(sex),
                    encrypt_text(contact),
                    patient_id,
                ))

    return len(rows)


