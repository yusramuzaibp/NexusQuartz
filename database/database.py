import os
import json
import psycopg
from dotenv import load_dotenv

load_dotenv()

def get_connection():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is missing from .env")

    return psycopg.connect(database_url)


def create_database():
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL
                )
            """)
            cursor.execute("""
                ALTER TABLE users
                ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'user'
                 """)

            
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS predictions (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL REFERENCES users(id),
                    condition_name TEXT NOT NULL,
                    result TEXT NOT NULL,
                    risk TEXT NOT NULL,
                    timestamp TEXT NOT NULL,
                    inputs_json TEXT
                )
            """)

            
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS patients (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    doctor_id INTEGER NOT NULL REFERENCES users(id),
                    patient_code TEXT NOT NULL,
                    name TEXT NOT NULL,
                    age INTEGER NOT NULL,
                    sex TEXT NOT NULL,
                    contact TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE (doctor_id, patient_code)
                )
            """)
            
            cursor.execute("""
                ALTER TABLE predictions
                ADD COLUMN IF NOT EXISTS patient_id INTEGER
                REFERENCES patients(id)
            """)

            cursor.execute("""
                ALTER TABLE patients
                ADD COLUMN IF NOT EXISTS visit_date DATE
                """)


def save_prediction_to_db(
    user_id, condition, result, risk, timestamp, inputs, patient_id=None
):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO predictions
                (
                    user_id,
                    condition_name,
                    result,
                    risk,
                    timestamp,
                    inputs_json,
                    patient_id
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    user_id,
                    condition,
                    result,
                    risk,
                    timestamp,
                    json.dumps(inputs),
                    patient_id,
                ),
            )



def get_user_predictions(user_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    p.id,
                    p.condition_name,
                    p.result,
                    p.risk,
                    p.timestamp,
                    p.inputs_json,
                    p.patient_id,
                    pt.name,
                    pt.patient_code,
                    pt.age,
                    pt.sex,
                    pt.contact
                FROM predictions p
                LEFT JOIN patients pt
                    ON p.patient_id = pt.id
                WHERE p.user_id = %s
                ORDER BY p.timestamp DESC
                """,
                (user_id,),
            )
            rows = cursor.fetchall()

    records = []

    for row in rows:
        try:
            inputs = json.loads(row[5]) if row[5] else {}
        except (TypeError, ValueError):
            inputs = {}

        records.append({
            "id": row[0],
            "condition": row[1],
            "result": row[2],
            "risk": row[3],
            "timestamp": row[4],
            "inputs": inputs,
            "patient_id": row[6],
            "patient_name": row[7] or "Unknown Patient",
            "patient_code": row[8] or "N/A",
            "age": row[9],
            "sex": row[10] or "N/A",
            "contact": row[11] or "N/A",
        })

    return records


def clear_user_predictions(user_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                "DELETE FROM predictions WHERE user_id = %s",
                (user_id,),
            )


def create_patient(
    doctor_id, patient_code, name, age, sex,
    visit_date, contact=""
):
    try:
        with get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO patients
                    (doctor_id, patient_code, name, age, sex,
                     visit_date, contact)
                    VALUES (%s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        doctor_id,
                        patient_code.strip(),
                        name.strip(),
                        age,
                        sex,
                        visit_date,
                        contact.strip(),
                    ),
                )

        return True, "Patient saved successfully."

    except Exception as e:
        if "unique" in str(e).lower():
            return False, "This patient code is already registered."
        return False, f"Could not save patient: {e}"


def get_patients(doctor_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    id,
                    patient_code,
                    name,
                    age,
                    sex,
                    contact,
                    created_at,
                    visit_date
                FROM patients
                WHERE doctor_id = %s
                ORDER BY name
                """,
                (doctor_id,),
            )
            rows = cursor.fetchall()

    return [
        {
            "id": row[0],
            "patient_code": row[1],
            "name": row[2],
            "age": row[3],
            "sex": row[4],
            "contact": row[5],
            "created_at": row[6],
            "visit_date": row[7],
        }
        for row in rows
    ]

def get_or_create_patient(doctor_id, name, age, sex, contact):
    contact = contact.strip()

    with get_connection() as conn:
        with conn.cursor() as cursor:

            # Check whether this patient already exists
            cursor.execute(
                """
                SELECT id
                FROM patients
                WHERE doctor_id = %s AND contact = %s
                LIMIT 1
                """,
                (doctor_id, contact),
            )

            existing_patient = cursor.fetchone()

            if existing_patient:
                return existing_patient[0]

            # Create a new patient if not found
            import uuid
            patient_code = "PAT-" + uuid.uuid4().hex[:10].upper()

            cursor.execute(
                """
                INSERT INTO patients
                (doctor_id, patient_code, name, age, sex, contact, visit_date)
                VALUES (%s, %s, %s, %s, %s, %s, CURRENT_DATE)
                RETURNING id
                """,
                (doctor_id, patient_code, name, age, sex, contact),
            )

            new_patient = cursor.fetchone()

            return new_patient[0]


def get_all_users():
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                SELECT id, name, email
                FROM users
                ORDER BY id
            """)
            rows = cursor.fetchall()

    return [
        {
            "id": row[0],
            "name": row[1],
            "email": row[2],
        }
        for row in rows
    ]


