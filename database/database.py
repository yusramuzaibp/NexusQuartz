def get_or_create_patient(doctor_id, name, age, sex, contact=""):
    try:
        with get_connection() as conn:
            with conn.cursor() as cursor:

                # Check whether this patient already exists
                cursor.execute(
                    """
                    SELECT id
                    FROM patients
                    WHERE doctor_id = %s
                    AND name = %s
                    AND age = %s
                    AND sex = %s
                    AND contact = %s
                    LIMIT 1
                    """,
                    (doctor_id, name.strip(), age, sex, contact.strip()),
                )

                patient = cursor.fetchone()

                if patient:
                    return patient[0]

                # Insert a new patient with a temporary unique code
                temp_code = f"TEMP-{uuid.uuid4()}"

                cursor.execute(
                    """
                    INSERT INTO patients
                    (doctor_id, patient_code, name, age, sex, contact)
                    VALUES (%s, %s, %s, %s, %s, %s)
                    RETURNING id
                    """,
                    (
                        doctor_id,
                        temp_code,
                        name.strip(),
                        age,
                        sex,
                        contact.strip(),
                    ),
                )

                patient_id = cursor.fetchone()[0]

                # Generate globally unique patient code from database ID
                patient_code = f"P{patient_id:04d}"

                cursor.execute(
                    """
                    UPDATE patients
                    SET patient_code = %s
                    WHERE id = %s
                    """,
                    (patient_code, patient_id),
                )

                return patient_id

    except Exception as e:
        raise Exception(f"Could not get or create patient: {e}")

