def get_patients(doctor_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT id, patient_code, name, age, sex, contact, created_at
                FROM patients
                WHERE doctor_id = %s
                """,
                (doctor_id,),
            )
            rows = cursor.fetchall()

    patients = []
    for row in rows:
        try:
            patients.append({
                "id": row[0],
                "patient_code": row[1],
                "name": decrypt_text(row[2]),
                "age": decrypt_text(row[3]) if row[3] is not None else None,
                "sex": decrypt_text(row[4]),
                "contact": decrypt_text(row[5]) if row[5] is not None else "",
                "created_at": row[6],
            })
        except Exception as e:
            raise RuntimeError(
                f"Could not decrypt patient details for patient {row[0]}"
            ) from e

    patients.sort(key=lambda patient: (patient["name"] or "").casefold())
    return patients

def get_or_create_patient(doctor_id, name, age, sex, contact=""):
    try:
        clean_name = name.strip()
        clean_age = str(age)
        clean_sex = sex
        clean_contact = contact.strip()

        with get_connection() as conn:
            with conn.cursor() as cursor:
                # Ciphertexts use random nonces, so compare after decrypting.
                cursor.execute(
                    """
                    SELECT id, name, age, sex, contact
                    FROM patients
                    WHERE doctor_id = %s
                    """,
                    (doctor_id,),
                )
                existing_patients = cursor.fetchall()

                for row in existing_patients:
                    try:
                        stored_name = decrypt_text(row[1]) or ""
                        stored_age = decrypt_text(row[2])
                        stored_sex = decrypt_text(row[3]) or ""
                        stored_contact = decrypt_text(row[4]) or ""
                    except Exception as e:
                        raise RuntimeError(
                            f"Could not decrypt existing patient {row[0]}"
                        ) from e

                    if (
                        stored_name.strip().casefold() == clean_name.casefold()
                        and str(stored_age) == clean_age
                        and stored_sex == clean_sex
                        and stored_contact.strip() == clean_contact
                    ):
                        return row[0]

                temp_code = f"TEMP-{uuid.uuid4()}"
                cursor.execute(
                    """
                    INSERT INTO patients
                    (doctor_id, patient_code, name, age, sex, contact)
                    VALUES (%s, %s, %s, %s, %s, %s)
                    RETURNING id
                    """,
                    (
                        doctor_id,
                        temp_code,
                        encrypt_text(clean_name),
                        encrypt_text(clean_age),
                        encrypt_text(clean_sex),
                        encrypt_text(clean_contact),
                    ),
                )
                patient_id = cursor.fetchone()[0]

                patient_code = f"P{patient_id:04d}"
                cursor.execute(
                    """
                    UPDATE patients
                    SET patient_code = %s
                    WHERE id = %s
                    """,
                    (patient_code, patient_id),
                )

                return patient_id

    except Exception as e:
        raise Exception(f"Could not get or create patient: {e}") from e

