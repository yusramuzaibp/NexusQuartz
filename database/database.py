import os
import json
import psycopg
from dotenv import load_dotenv

load_dotenv()

def get_connection():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is missing from .env")

    return psycopg.connect(database_url)


def create_database():
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL
                )
            """)

            
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS predictions (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL REFERENCES users(id),
                    condition_name TEXT NOT NULL,
                    result TEXT NOT NULL,
                    risk TEXT NOT NULL,
                    timestamp TEXT NOT NULL,
                    inputs_json TEXT
                )
            """)

            
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS patients (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    doctor_id INTEGER NOT NULL REFERENCES users(id),
                    patient_code TEXT NOT NULL,
                    name TEXT NOT NULL,
                    age INTEGER NOT NULL,
                    sex TEXT NOT NULL,
                    contact TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE (doctor_id, patient_code)
                )
            """)
            
            cursor.execute("""
                ALTER TABLE predictions
                ADD COLUMN IF NOT EXISTS patient_id INTEGER
                REFERENCES patients(id)
            """)


def save_prediction_to_db(
    user_id, condition, result, risk, timestamp, inputs, patient_id=None
):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO predictions
                (
                    user_id,
                    condition_name,
                    result,
                    risk,
                    timestamp,
                    inputs_json,
                    patient_id
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    user_id,
                    condition,
                    result,
                    risk,
                    timestamp,
                    json.dumps(inputs),
                    patient_id,
                ),
            )


def get_user_predictions(user_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT condition_name, result, risk, timestamp, inputs_json, patient_id
                FROM predictions
                WHERE user_id = %s
                ORDER BY timestamp DESC
                """,
                (user_id,),
            )
            rows = cursor.fetchall()

    records = []
    for cond, result, risk, timestamp, inputs_json, patient_id in rows:
        try:
            inputs = json.loads(inputs_json) if inputs_json else {}
        except (TypeError, ValueError):
            inputs = {}

        records.append({
            "condition": cond,
            "result": result,
            "risk": risk,
            "timestamp": timestamp,
            "inputs": inputs,
            "patient_id": patient_id,
        })

    return records


def clear_user_predictions(user_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                "DELETE FROM predictions WHERE user_id = %s",
                (user_id,),
            )


def create_patient(doctor_id, patient_code, name, age, sex, contact=""):
    try:
        with get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO patients
                    (doctor_id, patient_code, name, age, sex, contact)
                    VALUES (%s, %s, %s, %s, %s, %s)
                    """,
                    (
                        doctor_id,
                        patient_code.strip(),
                        name.strip(),
                        age,
                        sex,
                        contact.strip(),
                    ),
                )
        return True, "Patient registered successfully."

    except Exception as e:
        if "unique" in str(e).lower():
            return False, "This patient code is already registered."
        return False, f"Could not register patient: {e}"


