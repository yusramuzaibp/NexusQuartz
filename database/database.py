def get_user_predictions(user_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    p.id,
                    p.condition_name,
                    p.result,
                    p.risk,
                    p.timestamp,
                    p.inputs_json,
                    p.patient_id,
                    pt.name,
                    pt.patient_code,
                    pt.age,
                    pt.sex,
                    pt.contact
                FROM predictions p
                LEFT JOIN patients pt
                    ON p.patient_id = pt.id
                WHERE p.user_id = %s
                ORDER BY p.timestamp DESC
                """,
                (user_id,),
            )
            rows = cursor.fetchall()

    records = []
    for row in rows:
        try:
            inputs = decrypt_json(row[5]) if row[5] else {}
            patient_name = decrypt_text(row[7]) if row[7] else "Unknown Patient"
            patient_age = decrypt_text(row[9]) if row[9] is not None else None
            patient_sex = decrypt_text(row[10]) if row[10] else "N/A"
            patient_contact = decrypt_text(row[11]) if row[11] else "N/A"
        except Exception as e:
            raise RuntimeError(
                f"Could not decrypt patient or prediction data for record {row[0]}"
            ) from e

        records.append({
            "id": row[0],
            "condition": row[1],
            "result": row[2],
            "risk": row[3],
            "timestamp": row[4],
            "inputs": inputs,
            "patient_id": row[6],
            "patient_name": patient_name,
            "patient_code": row[8] or "N/A",
            "age": patient_age,
            "sex": patient_sex,
            "contact": patient_contact,
        })

    return records

